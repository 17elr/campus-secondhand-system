const assert=require('node:assert/strict')
const {chromium}=require(process.argv[2]||'playwright')

async function main(){
  const browser=await chromium.launch({channel:'msedge',headless:true})
  try{
    const page=await browser.newPage()
    const errors=[]
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto('http://127.0.0.1:15173')
    await page.getByRole('dialog',{name:'欢迎回到拾光集市'}).waitFor()
    await page.getByRole('button',{name:'还没有账号？立即注册',exact:true}).click()
    const username='authcheck_'+Date.now()
    await page.getByPlaceholder('同学们如何称呼你',{exact:true}).fill('注册测试同学')
    await page.getByPlaceholder('输入用户名',{exact:true}).fill(username)
    await page.getByPlaceholder('输入密码',{exact:true}).fill('test123456')
    await page.getByRole('button',{name:'注册并登录',exact:true}).click()
    await page.getByRole('dialog',{name:'加入校园好物循环'}).waitFor({state:'hidden'})
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('campus-user')).role),'USER')
    await page.locator('.goods-card').first().waitFor()
    await page.locator('.profile').click()
    await page.getByRole('button',{name:'退出登录',exact:true}).click()
    await page.getByRole('button',{name:'已有账号？返回登录',exact:true}).click()
    await page.getByPlaceholder('输入用户名',{exact:true}).fill(username)
    await page.getByPlaceholder('输入密码',{exact:true}).fill('test123456')
    await page.getByRole('button',{name:'登录集市',exact:true}).click()
    await page.getByRole('dialog',{name:'欢迎回到拾光集市'}).waitFor({state:'hidden'})
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('campus-user')).username),username)
    await page.locator('.profile').click()
    await page.getByRole('button',{name:'退出登录',exact:true}).click()
    await page.getByPlaceholder('输入用户名',{exact:true}).fill('admin')
    await page.getByPlaceholder('输入密码',{exact:true}).fill('admin123')
    await page.getByRole('button',{name:'登录集市',exact:true}).click()
    await page.getByRole('dialog',{name:'欢迎回到拾光集市'}).waitFor({state:'hidden'})
    await page.locator('.admin-console').waitFor()
    await page.locator('.recent-item').first().waitFor()
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('campus-user')).role),'ADMIN')
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({registration:true,relogin:true,adminConsole:true,goodsLoaded:true,pageErrors:errors}))
  }finally{await browser.close()}
}
main().catch(error=>{console.error(error);process.exit(1)})
