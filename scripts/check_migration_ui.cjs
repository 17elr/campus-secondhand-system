const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs/promises')
const {chromium} = require(process.argv[2] || process.env.PLAYWRIGHT_MODULE || 'playwright')

async function main() {
  const output = path.resolve(__dirname, '../docs/screenshots')
  await fs.mkdir(output, {recursive: true})
  const browser = await chromium.launch({channel: process.env.CI ? 'chromium' : 'msedge', headless: true})
  const errors = []
  try {
    const context = await browser.newContext({viewport: {width: 1440, height: 1000}})
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.message))
    await page.goto('http://127.0.0.1:15173')
    const dialog = page.getByRole('dialog', {name: '欢迎回到拾光集市'})
    await dialog.waitFor()
    await page.getByPlaceholder('输入用户名', {exact: true}).fill('student')
    await page.getByPlaceholder('输入密码', {exact: true}).fill('123456')
    await page.getByRole('button', {name: '登录集市', exact: true}).click()
    await dialog.waitFor({state: 'hidden'})
    await page.locator('.goods-card').first().waitFor()
    await page.locator('.el-message').waitFor({state: 'hidden'})
    await page.screenshot({animations: 'disabled',path: path.join(output, 'market.png'), fullPage: true})
    await page.reload()
    await page.locator('.profile').filter({hasText: '林同学'}).waitFor()
    assert.equal(await page.getByRole('dialog', {name: '欢迎回到拾光集市'}).count(), 0)
    await page.getByRole('button', {name: '打开站内通知', exact: true}).click()
    const notices = page.getByRole('dialog', {name: '站内通知'})
    await notices.locator('.message-item').first().waitFor()
    await page.screenshot({animations: 'disabled',path: path.join(output, 'notifications.png')})
    const retained = await notices.locator('.message-item').count()
    await page.route('**/api/notifications*', route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({message: '通知服务暂不可用，请稍后重试'})}))
    await page.keyboard.press('Escape')
    await notices.waitFor({state: 'hidden'})
    await page.getByRole('button', {name: '打开站内通知', exact: true}).click()
    await notices.getByRole('alert').waitFor()
    assert.equal(await notices.locator('.message-item').count(), retained)
    await page.screenshot({animations: 'disabled', path: path.join(output, 'notifications-outage.png')})
    await page.unroute('**/api/notifications*')
    await page.keyboard.press('Escape')
    await page.getByRole('dialog', {name: '站内通知'}).waitFor({state: 'hidden'})
    // localStorage is a display cache: tampering must not grant an admin session.
    await page.evaluate(() => localStorage.setItem('campus-user', JSON.stringify({id: 2, role: 'ADMIN', nickname: '伪造管理员'})))
    await page.reload()
    await page.locator('.profile').filter({hasText: '林同学'}).waitFor()
    assert.equal(await page.locator('.admin-console').count(), 0)
    const adminResult = await page.evaluate(async () => (await fetch('/api/admin/users', {headers: {'X-User-Role': 'ADMIN'}})).status)
    assert.equal(adminResult, 403)
    await page.setViewportSize({width: 390, height: 844})
    await page.screenshot({animations: 'disabled',path: path.join(output, 'market-mobile.png'), fullPage: true})
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile page overflows')
    await page.setViewportSize({width: 1440, height: 1000})
    await page.locator('.profile').click()
    await page.getByRole('button', {name: '退出登录', exact: true}).click()
    await dialog.waitFor()
    await page.getByPlaceholder('输入用户名', {exact: true}).fill('admin')
    await page.getByPlaceholder('输入密码', {exact: true}).fill('admin123')
    await page.getByRole('button', {name: '登录集市', exact: true}).click()
    await page.locator('.admin-console .recent-item').first().waitFor()
    await page.screenshot({animations: 'disabled',path: path.join(output, 'admin.png'), fullPage: true})
    await page.getByRole('button', {name: '通知投递', exact: true}).click()
    await page.getByRole('dialog', {name: '通知投递记录'}).waitFor()
    await page.screenshot({animations: 'disabled',path: path.join(output, 'outbox.png')})
    assert.deepEqual(errors, [])
    console.log(JSON.stringify({login: true, sessionRestored: true, forgedLocalStorageRejected: true, notifications: true, mobile: true, admin: true, outbox: true, pageErrors: errors}))
  } finally {
    await browser.close()
  }
}
main().catch(error => {console.error(error); process.exit(1)})
